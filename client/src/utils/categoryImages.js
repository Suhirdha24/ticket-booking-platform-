const DEFAULT_GENERIC_IMAGE =
  'https://images.unsplash.com/photo-1540747913346-19e32dc3e97e?w=1200&auto=format&fit=crop&q=80';

export function getEventImage(event) {
  if (!event) return DEFAULT_GENERIC_IMAGE;

  // If the event already has a specific custom image (not the old generic default)
  if (
    event.bannerUrl &&
    event.bannerUrl !== DEFAULT_GENERIC_IMAGE &&
    !event.bannerUrl.includes('photo-1540747913346-19e32dc3e97e')
  ) {
    return event.bannerUrl;
  }

  const pool = CATEGORY_IMAGE_POOLS[event.category] || CATEGORY_IMAGE_POOLS['Concert'];
  const key = event.title || event._id || event.name || 'default';

  // Compute deterministic hash index so the same event gets the same stunning image
  let hash = 0;
  for (let i = 0; i < key.length; i++) {
    hash = (hash << 5) - hash + key.charCodeAt(i);
    hash |= 0;
  }
  const index = Math.abs(hash) % pool.length;
  return pool[index];
}
